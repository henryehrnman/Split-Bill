#!/usr/bin/env node
// Copies the shared rules engine into the Edge Function tree so there is still one copy to edit.
// Run before every deploy and before supabase tests: node scripts/copy-shared.mjs
import {copyFileSync, mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'mobile', 'src', 'lib');
const to = join(root, 'supabase', 'functions', '_shared');
const files = ['domain.ts', 'split.ts', 'money.ts', 'fakeOcr.ts', 'seed.ts'];

mkdirSync(to, {recursive: true});
for (const f of files) copyFileSync(join(from, f), join(to, f));
writeFileSync(join(to, 'README.md'), 'Generated by scripts/copy-shared.mjs from mobile/src/lib. Do not edit here.\n');
console.log(`Copied ${files.length} files to supabase/functions/_shared`);
